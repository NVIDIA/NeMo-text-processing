"""Export the installed Python/sacremoses character properties at build time."""

import unicodedata
from argparse import ArgumentParser
from importlib.metadata import version
from pathlib import Path

from sacremoses import MosesDetokenizer
from sacremoses.util import CJKChars


def ranges(values: list[int]) -> list[tuple[int, int]]:
    """Coalesce exact codepoint membership into sorted closed intervals."""
    result: list[tuple[int, int]] = []
    for value in sorted(set(values)):
        if result and result[-1][1] + 1 == value:
            result[-1] = (result[-1][0], value)
        else:
            result.append((value, value))
    return result


def export(path: Path) -> None:
    """Write immutable C++ tables; runtime processing needs no Python."""
    properties = {
        "whitespace": ranges([c for c in range(0x110000) if chr(c).isspace()]),
        "alpha": ranges(list(map(ord, MosesDetokenizer.IsAlpha))),
        "currency_symbols": ranges(list(map(ord, MosesDetokenizer.IsSc))),
        "cjk": CJKChars.ranges,
    }
    lines = [
        "// Generated by export_text_tables.py; do not edit.",
        f"// Python Unicode {unicodedata.unidata_version}; sacremoses {version('sacremoses')}.",
        "// Sacremoses-derived tables are covered by LICENSE.sacremoses.",
        "#pragma once",
        "namespace tn_text {",
        "struct Range { char32_t first, last; };",
    ]
    for name, items in properties.items():
        lines.append(f"inline constexpr Range {name}[] = {{")
        lines.extend(f"  {{0x{a:x},0x{b:x}}}," for a, b in items)
        lines.append("};")
    lines.extend(["}", ""])
    path.write_text("\n".join(lines))


if __name__ == "__main__":
    parser = ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    export(parser.parse_args().output)
